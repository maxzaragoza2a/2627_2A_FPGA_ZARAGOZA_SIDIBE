library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

library pll;
use pll.all;

entity telecran is
    port (
        -- FPGA
        i_clk_50: in std_logic;

        -- HDMI
        io_hdmi_i2c_scl       : inout std_logic;
        io_hdmi_i2c_sda       : inout std_logic;
        o_hdmi_tx_clk        : out std_logic;
        o_hdmi_tx_d          : out std_logic_vector(23 downto 0);
        o_hdmi_tx_de         : out std_logic;
        o_hdmi_tx_hs         : out std_logic;
        i_hdmi_tx_int        : in std_logic;
        o_hdmi_tx_vs         : out std_logic;

        -- KEYs
        i_rst_n : in std_logic;
		  
		-- LEDs
		o_leds : out std_logic_vector(9 downto 0);
		o_de10_leds : out std_logic_vector(7 downto 0);

		-- Coder
		i_left_ch_a : in std_logic;
		i_left_ch_b : in std_logic;
		i_left_pb : in std_logic;
		i_right_ch_a : in std_logic;
		i_right_ch_b : in std_logic;
		i_right_pb : in std_logic
    );
end entity telecran;

architecture rtl of telecran is
	component I2C_HDMI_Config 
		port (
			iCLK : in std_logic;
			iRST_N : in std_logic;
			I2C_SCLK : out std_logic;
			I2C_SDAT : inout std_logic;
			HDMI_TX_INT  : in std_logic
		);
	 end component;

	component hdmi_controler
		generic (
			h_res : positive := 720;
			v_res : positive := 480;
			h_sync : positive := 61;
			h_fp : positive := 58;
			h_bp : positive := 18;
			v_sync : positive := 5;
			v_fp : positive := 30;
			v_bp : positive := 9
		);
		port (
			i_clk : in std_logic;
			i_rst_n : in std_logic;
			o_hdmi_hs : out std_logic;
			o_hdmi_vs : out std_logic;
			o_hdmi_de : out std_logic;
			o_pixel_en : out std_logic;
			o_pixel_address : out natural range 0 to h_res * v_res - 1;
			o_x_counter : out natural range 0 to h_res - 1;
			o_y_counter : out natural range 0 to v_res - 1
		);
	end component;

	component pll
		port (
			refclk : in std_logic;
			rst : in std_logic;
			outclk_0 : out std_logic;
			locked : out std_logic
		);
	end component;

    constant h_res : natural := 720;
    constant v_res : natural := 480;

	-- Anti-rebond des encodeurs : 27 000 cycles a 27 MHz = 1 ms
	-- + decodage complet des transitions (g_full_decode) : une voie qui
	-- oscille quand l'encodeur est immobile ne fait plus deriver la position
	constant c_debounce : natural := 27_000;

	-- Sensibilite des encodeurs : la position avance de 1 pixel toutes les
	-- 2**c_div_log2 transitions (1 cycle de quadrature = 4 transitions)
	--   1 : 2 pixels par cycle   2 : 1 pixel par cycle   3 : 1 pixel tous les 2 cycles
	constant c_div_log2 : natural := 2;

	signal s_clk_27 : std_logic;
	signal s_rst_n : std_logic;	-- holds reset as long as pll is not locked

	-- Position du pixel donnee par les encodeurs (bloquee dans l'ecran)
	signal s_enc_x : std_logic_vector(9 downto 0);
	signal s_enc_y : std_logic_vector(9 downto 0);

	-- Framebuffer : 1 bit par pixel (1 = deja dessine, 0 = vide)
	-- Port A : ecriture a l'adresse du stylet (encodeurs)
	-- Port B : lecture a l'adresse du pixel en cours d'affichage (HDMI)
	signal s_wr_addr : natural range 0 to h_res * v_res - 1;
	signal s_rd_addr : natural range 0 to h_res * v_res - 1;
	signal s_rd_data : std_logic_vector(0 downto 0);
begin
	-- Debug : position x sur les LED de la mezzanine, y sur les LED de la DE10-Nano
	o_leds <= s_enc_x;
	o_de10_leds <= s_enc_y(7 downto 0);
	
	-- Frequency for HDMI is 27MHz generated by this PLL
	pll0 : component pll 
		port map (
			refclk => i_clk_50,
			rst => not(i_rst_n),
			outclk_0 => s_clk_27,
			locked => s_rst_n
		);

	-- Configures the ADV7513 for 480p
	I2C_HDMI_Config0 : component I2C_HDMI_Config 
		port map (
			iCLK => i_clk_50,
			iRST_N => i_rst_n,
			I2C_SCLK => io_hdmi_i2c_scl,
			I2C_SDAT => io_hdmi_i2c_sda,
			HDMI_TX_INT => i_hdmi_tx_int
	 );

	-- Generates HDMI synchronisation signals and pixel coordinates
	hdmi_controler0 : component hdmi_controler
		generic map (
			h_res => h_res,
			v_res => v_res
		)
		port map (
			i_clk => s_clk_27,
			i_rst_n => s_rst_n,
			o_hdmi_hs => o_hdmi_tx_hs,
			o_hdmi_vs => o_hdmi_tx_vs,
			o_hdmi_de => o_hdmi_tx_de,
			o_pixel_en => open,
			o_pixel_address => s_rd_addr,
			o_x_counter => open,
			o_y_counter => open
		);

	o_hdmi_tx_clk <= s_clk_27;

	-- Encodeur gauche : position horizontale (0 a h_res-1)
	encoder_x : entity work.encoder
		generic map (
			g_width => 10,
			g_saturate => true,
			g_debounce => c_debounce,
			g_full_decode => true,
			g_div_log2 => c_div_log2,
			g_max => h_res - 1
		)
		port map (
			i_clk => s_clk_27,
			i_rst_n => s_rst_n,
			i_ch_a => i_left_ch_a,
			i_ch_b => i_left_ch_b,
			o_value => s_enc_x
		);

	-- Encodeur droit : position verticale (0 a v_res-1)
	encoder_y : entity work.encoder
		generic map (
			g_width => 10,
			g_saturate => true,
			g_debounce => c_debounce,
			g_full_decode => true,
			g_div_log2 => c_div_log2,
			g_max => v_res - 1
		)
		port map (
			i_clk => s_clk_27,
			i_rst_n => s_rst_n,
			i_ch_a => i_right_ch_a,
			i_ch_b => i_right_ch_b,
			o_value => s_enc_y
		);

	-- Adresse d'ecriture : meme convention que le controleur HDMI
	-- (adresse = x + y * h_res), pour que l'ecriture et la lecture
	-- designent le meme pixel.
	s_wr_addr <= to_integer(unsigned(s_enc_x)) + to_integer(unsigned(s_enc_y)) * h_res;

	-- Framebuffer en RAM double port (blocs M10K du FPGA)
	framebuffer : entity work.dpram
		generic map (
			mem_size => h_res * v_res,
			data_width => 1
		)
		port map (
			-- Port A : le stylet ecrit un '1' en permanence a sa position.
			-- Quand il se deplace, l'ancienne case garde son '1' : c'est la trace.
			i_clk_a => s_clk_27,
			i_addr_a => s_wr_addr,
			i_data_a => "1",
			i_we_a => '1',
			o_q_a => open,

			-- Port B : lecture seule par le controleur HDMI
			i_clk_b => s_clk_27,
			i_addr_b => s_rd_addr,
			i_data_b => "0",
			i_we_b => '0',
			o_q_b => s_rd_data
		);

	-- Couleur : blanc si le pixel a deja ete dessine, noir sinon.
	-- La lecture en RAM a un cycle de latence : la donnee sort au cycle
	-- suivant l'adresse, en meme temps que o_hdmi_tx_de (lui aussi registre
	-- dans hdmi_controler). Pas besoin de registre supplementaire.
	o_hdmi_tx_d <= (others => s_rd_data(0));
end architecture rtl;
